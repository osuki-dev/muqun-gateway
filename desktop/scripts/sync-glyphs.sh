#!/usr/bin/env bash
# Sync the App's glyph set into desktop/assets/glyphs and regenerate
# src/ui/glyphs.rs. The App (app/assets/glyphs) is the single icon source.
#   MUQUN_APP_DIR  path to the App checkout (default: ../app, sibling of the repo)
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
app="${MUQUN_APP_DIR:-$here/../../app}"
src="$app/assets/glyphs"
dst="$here/assets/glyphs"
out="$here/src/ui/glyphs.rs"

[ -d "$src" ] || { echo "no glyphs at $src (set MUQUN_APP_DIR)" >&2; exit 1; }

mkdir -p "$dst"
find "$dst" -maxdepth 1 -type f \( -name '*.svg' -o -name 'LICENSE-*' -o -name provenance.json \) -delete
export LC_ALL=C
cp "$src"/*.svg "$dst"/
for f in "$src"/LICENSE-* "$src"/provenance.json; do
  [ -f "$f" ] && cp "$f" "$dst"/
done

# OpenCode has no SVG in the App (app/src/components/opencode-icon.tsx draws a
# 2:3 block: top third solid, bottom two thirds at 45% alpha).
cat > "$dst/brand-opencode.svg" <<'SVG'
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><rect x="4" y="0" width="16" height="8" fill="currentColor"/><rect x="4" y="8" width="16" height="16" fill="currentColor" fill-opacity="0.45"/></svg>
SVG

pascal() { echo "$1" | awk -F- '{for(i=1;i<=NF;i++)printf "%s%s",toupper(substr($i,1,1)),substr($i,2)}'; }

names=$(cd "$dst" && ls *.svg | sed 's/\.svg$//' | sort)
{
  echo "// @generated by scripts/sync-glyphs.sh -- do not edit."
  echo "//! The App's icon set, embedded. One variant per SVG in \`assets/glyphs\`."
  echo
  echo "#![allow(dead_code)] // the full set is embedded; callers use what they need"
  echo
  echo "use blinc_layout::svg::{svg, Svg};"
  echo
  echo "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]"
  echo "pub enum Glyph {"
  for n in $names; do echo "    $(pascal "$n"),"; done
  echo "}"
  echo
  echo "impl Glyph {"
  echo "    pub const ALL: &'static [Glyph] = &["
  for n in $names; do echo "        Glyph::$(pascal "$n"),"; done
  echo "    ];"
  echo
  echo "    /// The SVG source: 24x24 viewBox, \`currentColor\`."
  echo "    pub const fn svg(self) -> &'static str {"
  echo "        match self {"
  for n in $names; do
    echo "            Glyph::$(pascal "$n") => include_str!(\"../../assets/glyphs/$n.svg\"),"
  done
  echo "        }"
  echo "    }"
  echo "}"
  cat <<'RS'

/// The brand mark for an agent kind; same mapping as the App's
/// `agentMarkKind`. Unknown kinds get the generic agent glyph.
pub fn agent_mark(kind: &str) -> Glyph {
    match kind {
        "opencode" => Glyph::BrandOpencode,
        "deepseek" => Glyph::BrandDeepseek,
        "t3" => Glyph::BrandT3,
        "codex" => Glyph::BrandCodex,
        "pi" => Glyph::BrandPi,
        "fx" => Glyph::BrandFx,
        "qoder" | "qodercli" | "qoder-cli" => Glyph::BrandQoder,
        "cursor" => Glyph::BrandCursor,
        "claude" | "claude-code" => Glyph::BrandClaude,
        "antigravity" | "agy" => Glyph::BrandAntigravity,
        _ => Glyph::Agent,
    }
}

/// A `size`x`size` icon element; colour it with `.tint(color)`.
pub fn icon(glyph: Glyph, size: f32) -> Svg {
    svg(glyph.svg()).square(size)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_an_svg_with_a_view_box() {
        // Interface glyphs are 24x24; some brand marks keep their own box.
        for g in Glyph::ALL {
            let s = g.svg();
            assert!(s.contains("<svg") && s.contains("viewBox=\""), "{g:?}");
            if !format!("{g:?}").starts_with("Brand") {
                assert!(s.contains("viewBox=\"0 0 24 24\""), "{g:?}");
            }
        }
    }

    #[test]
    fn agent_marks() {
        assert_eq!(agent_mark("claude-code"), Glyph::BrandClaude);
        assert_eq!(agent_mark("agy"), Glyph::BrandAntigravity);
        assert_eq!(agent_mark("qoder-cli"), Glyph::BrandQoder);
        assert_eq!(agent_mark("who"), Glyph::Agent);
    }
}
RS
} > "$out"

rustfmt --edition 2021 "$out"
echo "synced $(ls "$dst"/*.svg | wc -l) glyphs -> $out"
